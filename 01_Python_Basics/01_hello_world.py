# Single-line comment
print("Hello, World!")       # printing a string
print('Hello again!')        # single or double quotes both work

# print() with multiple values
print("My name is", "Abhishek")
print("Sum of 5 + 3 =", 5 + 3)

# print() with sep and end
print("Python", "is", "fun", sep="-")        # Python-is-fun
print("No newline here", end=" ")
print("| Same line")

# Multi-line string
print("""
This is
a multi-line
print statement.
""")
